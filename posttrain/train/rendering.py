"""Replay trusted local agent histories using the endpoint's Qwen3.5 template."""

import base64
import copy
import pickle
from array import array

from pydantic import BaseModel
from tinker_cookbook import renderers
from tinker_cookbook.renderers.qwen3_5 import Qwen3_5Renderer


class EndpointQwen35Renderer(Qwen3_5Renderer):
    def _strips_thinking_for(self, message, ctx):
        return message["role"] == "assistant" and ctx.idx <= ctx.last_user_index

    def _frames_produced_turn(self, message, ctx):
        return message["role"] == "assistant" and ctx.idx > ctx.last_user_index


def readable(value):
    if isinstance(value, BaseModel):
        return readable(
            dict(vars(value)) | (getattr(value, "__pydantic_extra__", None) or {})
        )
    if isinstance(value, dict):
        return {key: readable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [readable(item) for item in value]
    return value


def decode_response(value):
    if isinstance(value, str):
        # Native histories are trusted files generated by our local agent workers.
        value = pickle.loads(base64.b64decode(value))
    elif isinstance(value, dict) and "pickle" in value:
        value = pickle.loads(base64.b64decode(value["pickle"]))
    return readable(value)


def text_content(content):
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    return "".join(part["text"] for part in content if part["type"] == "text")


def assistant_message(response):
    response = decode_response(response)
    parts = []
    if response.get("reasoning_content"):
        parts.append({"type": "thinking", "thinking": response["reasoning_content"]})
    parts.append({"type": "text", "text": text_content(response.get("content"))})
    message = {"role": "assistant", "content": parts}
    if response.get("tool_calls"):
        message["tool_calls"] = [
            renderers.ToolCall(
                id=call["id"],
                function=renderers.ToolCall.FunctionBody(
                    name=call["function"]["name"],
                    arguments=call["function"]["arguments"],
                ),
            )
            for call in response["tool_calls"]
        ]
    return message


def history_messages(history):
    messages = []
    for item in history:
        kind = item["kind"]
        if kind == "text":
            if messages and messages[-1]["role"] == "user":
                messages[-1]["content"] += item["text"]
            else:
                messages.append({"role": "user", "content": item["text"]})
        elif kind == "system":
            messages.append({"role": "system", "content": item["text"]})
        elif kind == "raw_response":
            messages.append(assistant_message(item["response"]))
        elif kind == "tool_result":
            messages.append(
                {
                    "role": "tool",
                    "content": item["result"],
                    "tool_call_id": item["tool_call"]["id"],
                }
            )
        elif kind == "raw_input":
            value = decode_response(item["input"])
            if isinstance(value, list):
                messages.extend(value)
            elif value.get("role") == "assistant":
                messages.append(assistant_message(value))
            else:
                messages.append(
                    {"role": value["role"], "content": text_content(value["content"])}
                )
        else:
            raise ValueError(f"Unsupported history item: {kind}")
    return messages


def tool_specs(tools):
    specs = []
    for tool in tools:
        if "function" in tool:
            spec = copy.deepcopy(tool)
            spec["function"].pop("strict", None)
        else:
            body = tool.get("body", tool)
            params = body.get("parameters") or {
                "type": "object",
                "properties": body.get("properties", {}),
                "required": body.get("required", []),
                "additionalProperties": body.get("kwargs", {}).get(
                    "additional_properties", False
                ),
            }
            spec = {
                "type": "function",
                "function": {
                    "name": tool["name"],
                    "description": body.get("description", ""),
                    "parameters": params,
                },
            }
        spec["function"]["parameters"].setdefault("additionalProperties", False)
        specs.append(spec)
    return specs


def conversation(renderer, history, specs):
    messages = history_messages(history)
    system = (
        messages.pop(0)["content"]
        if messages and messages[0]["role"] == "system"
        else ""
    )
    return renderer.create_conversation_prefix_with_tools(specs, system) + messages


def render_turn(renderer, history, specs):
    target_index = max(
        (i for i, item in enumerate(history) if item["kind"] == "raw_response"),
        default=-1,
    )
    if target_index < 0:
        raise ValueError("No assistant response in history")
    prefix = conversation(renderer, history[:target_index], specs)
    target = assistant_message(history[target_index]["response"])
    prompt = renderer.build_generation_prompt(prefix).to_ints()
    full, _ = renderer.build_supervised_example(
        prefix + [target], train_on_what=renderers.TrainOnWhat.LAST_ASSISTANT_MESSAGE
    )
    tokens = full.to_ints()
    if tokens[: len(prompt)] != prompt:
        raise ValueError("Supervised prompt does not equal inference-time token prefix")
    if len(tokens) <= len(prompt):
        raise ValueError("Empty assistant target")
    return {
        "input_ids": tokens[:-1],
        "target_ids": tokens[1:],
        "weights": [0.0] * (len(prompt) - 1) + [1.0] * (len(tokens) - len(prompt)),
        "prompt_tokens": len(prompt),
        "sequence_tokens": len(tokens),
        "target_tokens": len(tokens) - len(prompt),
    }


def merge_turns(records):
    groups = []
    current = []
    for record in records:
        tokens = array("I", record["input_ids"])
        tokens.append(record["target_ids"][-1])
        prompt = record["prompt_tokens"]
        if not 0 < prompt < len(tokens):
            raise ValueError("Invalid assistant span")
        if current and (
            prompt < len(current[-1][0])
            or tokens[: len(current[-1][0])] != current[-1][0]
        ):
            groups.append(current)
            current = []
        current.append((tokens, prompt, record.get("turn")))
    if current:
        groups.append(current)
    merged = []
    for group in groups:
        final = group[-1][0]
        weights = [0.0] * (len(final) - 1)
        spans = []
        for tokens, prompt, turn in group:
            if final[: len(tokens)] != tokens:
                raise ValueError("Assistant turn is not a final-sequence prefix")
            weights[prompt - 1 : len(tokens) - 1] = [1.0] * (len(tokens) - prompt)
            spans.append({"turn": turn, "start": prompt, "end": len(tokens)})
        merged.append(
            {
                "input_ids": list(final[:-1]),
                "target_ids": list(final[1:]),
                "weights": weights,
                "prompt_tokens": group[0][1],
                "sequence_tokens": len(final),
                "target_tokens": int(sum(weights)),
                "assistant_spans": spans,
                "prefix_verified_turns": len(group),
                "turns": [item[2] for item in group],
            }
        )
    return merged
